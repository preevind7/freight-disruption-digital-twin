(function () {
  "use strict";
  const FDT = window.FDT = window.FDT || {};
  FDT.pages = FDT.pages || {};

  function kind(severity) {
    return severity === "High" ? "high" : severity === "Moderate" ? "moderate" : "info";
  }

  function render(root) {
    const corridor = FDT.data.getCorridor(FDT.state.corridorId);
    const forecast = FDT.mlCorridor && FDT.mlCorridor.get(corridor.id);
    const alerts = FDT.data.alerts.filter(function (alert) { return alert.corridorId === corridor.id; });
    const open = alerts.filter(function (alert) { return !FDT.state.closedAlerts.includes(alert.id); });
    const order = { High: 0, Moderate: 1, Info: 2 };
    open.sort(function (a, b) { return (order[a.severity] - order[b.severity]) || String(a.segmentId).localeCompare(String(b.segmentId)); });
    const count = function (sev) { return open.filter(function (a) { return a.severity === sev; }).length; };

    root.innerHTML =
      '<header class="page-heading"><div><p class="small muted">ACCOUNT · <span class="simulated">Generated by the ML forecast</span></p><h1>Alerts</h1><p>' + FDT.escapeHtml(corridor.name) +
      (forecast ? ' · forecast for ' + FDT.escapeHtml(forecast.date) + ' · generated ' + FDT.escapeHtml(forecast.generated_at.slice(11, 16)) + ' IST' : "") + '</p></div>' +
      '<div class="page-actions"><button type="button" class="button" id="alerts-read-all">Mark all as read</button></div></header>' +
      '<section class="kpi-grid ml-kpis--3" aria-label="Alert summary">' +
      '<article class="kpi-card kpi-card--risk"><span class="kpi-card__label">High</span><strong class="kpi-card__value number">' + count("High") + '</strong><span class="kpi-card__note">Heavy-rain alert, road closure or risk ≥ 0.60</span></article>' +
      '<article class="kpi-card"><span class="kpi-card__label">Moderate</span><strong class="kpi-card__value number">' + count("Moderate") + '</strong><span class="kpi-card__note">Risk ≥ 0.50, festival traffic or slow live traffic</span></article>' +
      '<article class="kpi-card"><span class="kpi-card__label">Info</span><strong class="kpi-card__value number">' + count("Info") + '</strong><span class="kpi-card__note">Forecast status</span></article></section>' +
      '<section class="card"><div class="card__header"><div><h2>Open alerts</h2><p>Select an alert to open its segment. Closed alerts stay hidden until the next forecast day.</p></div></div><div id="alerts-list" class="alert-mini-list"></div></section>';

    const list = root.querySelector("#alerts-list");
    if (!open.length) {
      list.innerHTML = '<div class="empty-state"><h3>No open alerts</h3><p>The models found no heavy rain or high-risk hours on this corridor today.</p></div>';
    }
    open.forEach(function (alert) {
      const unread = !FDT.state.alertsRead.includes(alert.id);
      const row = document.createElement("article");
      row.className = "alert-mini";
      row.innerHTML = '<span class="alert-mini__severity alert-mini__severity--' + FDT.escapeHtml(alert.severity.toLowerCase()) + '" aria-label="' + FDT.escapeHtml(alert.severity) + ' alert">' + (alert.severity === "High" ? "!" : alert.severity === "Moderate" ? "△" : "i") + '</span>' +
        '<div style="flex:1"><a href="#/segment/' + encodeURIComponent(alert.segmentId) + '">' + (unread ? "<strong>" : "") + FDT.escapeHtml(alert.title) + (unread ? "</strong>" : "") + '</a><small>' + FDT.escapeHtml(alert.time) + ' · <span class="pill pill--' + kind(alert.severity) + '">' + FDT.escapeHtml(alert.severity) + '</span></small></div>' +
        '<button type="button" class="button button--subtle" data-close="' + FDT.escapeHtml(alert.id) + '">Close</button>';
      row.querySelector("a").addEventListener("click", function () {
        FDT.store.update(function (state) { if (!state.alertsRead.includes(alert.id)) state.alertsRead.push(alert.id); });
      });
      list.append(row);
    });
    list.querySelectorAll("[data-close]").forEach(function (button) {
      button.addEventListener("click", function () {
        const id = button.getAttribute("data-close");
        FDT.store.update(function (state) { if (!state.closedAlerts.includes(id)) state.closedAlerts.push(id); });
        FDT.toast("Alert closed.");
        FDT.router.render();
      });
    });
    root.querySelector("#alerts-read-all").addEventListener("click", function () {
      FDT.store.update(function (state) { open.forEach(function (a) { if (!state.alertsRead.includes(a.id)) state.alertsRead.push(a.id); }); });
      FDT.router.render();
    });
  }

  FDT.pages.alerts = { title: "Alerts", render: render, destroy: function () {} };
}());
